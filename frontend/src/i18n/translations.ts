/**
 * Format bytes to a locale-aware representation
 */
export function formatBytes(bytes: number | string, lang: string): string {
  const num = typeof bytes === "string" ? parseInt(bytes, 10) : bytes;
  if (isNaN(num)) return "0 B";
  if (num === 0) {
    if (lang === "hi") return "0 बाइट";
    if (lang === "te") return "0 బైట్లు";
    return "0 Bytes";
  }
  const k = 1024;
  const sizes = ["Bytes", "KB", "MB", "GB"];
  const sizesHi = ["बाइट", "केबी", "एमबी", "जीबी"];
  const sizesTe = ["బైట్లు", "KB", "MB", "GB"];
  
  const i = Math.floor(Math.log(num) / Math.log(k));
  const val = parseFloat((num / Math.pow(k, i)).toFixed(2));
  
  // Format numbers using locale
  const locale = lang === "hi" ? "hi-IN" : lang === "te" ? "te-IN" : "en-IN";
  const formattedVal = new Intl.NumberFormat(locale).format(val);
  
  const unitList = lang === "hi" ? sizesHi : lang === "te" ? sizesTe : sizes;
  return `${formattedVal} ${unitList[i]}`;
}

/**
 * Format timestamp in UTC or locale-specific string
 */
export function formatDate(dateStr: string, lang: string): string {
  const date = new Date(dateStr);
  if (isNaN(date.getTime())) return dateStr;
  
  const locale = lang === "hi" ? "hi-IN" : lang === "te" ? "te-IN" : "en-IN";
  
  return date.toLocaleString(locale, {
    timeZone: "UTC",
    year: "numeric",
    month: "short",
    day: "numeric",
    hour: "2-digit",
    minute: "2-digit",
    second: "2-digit",
    hour12: true
  }) + " UTC";
}
